"""Task 1: Scraping the data from books.toscrape.com"""

import requests
from bs4 import BeautifulSoup
from urllib.parse import urljoin

base_url = "http://books.toscrape.com/catalogue/page-{}.html"

books = []

for page in range(1, 6):  # scrape first 5 pages
    url = base_url.format(page)
    response = requests.get(url)
    soup = BeautifulSoup(response.text, "html.parser")

    for book in soup.select("article.product_pod"):
        title = book.h3.a["title"]
        price = book.select_one("p.price_color").text
        star_rating = book.p["class"][1]
        availability = book.select_one("p.availability").text.strip()


        book_url = "http://books.toscrape.com/catalogue/" + book.h3.a["href"]
        book_response = requests.get(book_url)
        book_soup = BeautifulSoup(book_response.text, "html.parser")

        breadcrumb = book_soup.select("ul.breadcrumb li a")
        if len(breadcrumb) >=3:
          category = breadcrumb[2].text.strip()

        books.append({
            "title": title,
            "price": price,
            "star_rating": star_rating,
            "availability": availability,
            "category": category
        })

print(f"Scraped {len(books)} books")

df = pd.DataFrame(books)
