df['category'].unique()

"""Task 2: cleaning the scraped fields into proper types

1. Strip the currency symbol from price and convert it to a float column price_gbp.
2. Convert the text star rating (One…Five) into an integer column rating (1–5).
3. Parse the availability text into a boolean column in_stock.
4. If any field fails to parse for a given row (e.g., unexpected text), handle it with the median-imputation approach for numeric fields or drop the row (state and justify your choice) — do not leave the pipeline crashing on messy rows.
"""

df['price_gbp'] = df['price'].str.replace("Â£","").astype(float)

rating = {"One":1, "Two": 2, "Three":3, "Four":4, "Five":5}
df['rating'] = df['star_rating'].map(rating)

df['in_stock'] = df['availability'].str.contains('In stock')

df["price_gbp"] = pd.to_numeric(df["price_gbp"], errors="coerce")
median_price = df["price_gbp"].median()
df["price_gbp"].fillna(median_price, inplace=True)

df["rating"] = pd.to_numeric(df["rating"], errors="coerce")
median_rating = df["rating"].median()
df["rating"].fillna(median_rating, inplace=True)

df.dropna(subset=["in_stock", "category"], inplace=True)

df.head()

"""Task 3: convert price_gbp into price_inr, 1 GBP = 105.50 INR."""

df['price_inr'] = df['price_gbp'] * 105.50

